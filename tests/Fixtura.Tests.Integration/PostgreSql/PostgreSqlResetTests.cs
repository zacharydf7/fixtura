using Npgsql;

namespace Fixtura.Tests.Integration.PostgreSql;

public class PostgreSqlResetTests
{
    [Fact]
    public async Task ResetDataAsync_ShouldEmptyEveryTable_WhenTablesReferenceEachOtherOrArePartitioned()
    {
        await using ResetDatabase db = await ResetDatabase.CreateAsync();

        await db.Fixture.ResetDataAsync();

        Assert.Equal(0L, await db.ScalarAsync(
            """SELECT (SELECT COUNT(*) FROM "Customers") + (SELECT COUNT(*) FROM "Orders") + (SELECT COUNT(*) FROM "Readings")"""));
    }

    [Fact]
    public async Task ResetDataAsync_ShouldRestartIdentitySerialAndDefaultSequences_WhenRowsWereAdded()
    {
        await using ResetDatabase db = await ResetDatabase.CreateAsync();

        await db.Fixture.ResetDataAsync();

        object? ids = await db.ScalarAsync("""
            INSERT INTO "Customers" DEFAULT VALUES;
            INSERT INTO "Orders" ("CustomerId") VALUES (1);
            INSERT INTO "Invoices" DEFAULT VALUES;
            INSERT INTO "Readings" ("Day") VALUES ('2026-06-01');
            SELECT ARRAY[(SELECT "Id" FROM "Customers"), (SELECT "Id" FROM "Orders"), (SELECT "Id" FROM "Invoices"),
                (SELECT "Number" FROM "Readings")]
            """);
        Assert.Equal([1, 1, 100, 50], (int[])ids!);
    }

    // SharedNumbers feeds the kept Countries and the emptied Tickets; HiLoNumbers feeds no default, as EF Core's HiLo.
    [Fact]
    public async Task ResetDataAsync_ShouldKeepCountingSequences_WhenAKeptTableOrTheAppDrawsFromThem()
    {
        await using ResetDatabase db = await ResetDatabase.CreateAsync();

        await db.Fixture.ResetDataAsync();

        object? next = await db.ScalarAsync("""SELECT ARRAY[nextval('"SharedNumbers"'), nextval('"HiLoNumbers"')]""");
        Assert.Equal([202L, 301L], (long[])next!);
    }

    [Fact]
    public async Task ResetDataAsync_ShouldKeepTheListedTablesAndAnyMigrationsHistory_WhenTheyAreWrittenAnyWay()
    {
        await using ResetDatabase db = await ResetDatabase.CreateAsync();

        await db.Fixture.ResetDataAsync();

        Assert.Equal(5L, await db.ScalarAsync("""
            SELECT (SELECT COUNT(*) FROM "Countries") + (SELECT COUNT(*) FROM ref."Regions") + (SELECT COUNT(*) FROM ref."Zones")
                + (SELECT COUNT(*) FROM "__EFMigrationsHistory") + (SELECT COUNT(*) FROM "MigrationLog")
            """));
    }

    [Fact]
    public async Task ResetDataAsync_ShouldNotCheckTheKeptNames_WhenTheAppHasNotCreatedItsDatabaseYet()
    {
        await PostgresNotesFixture.SkipWithoutServerAsync();
        await using var fixture = new PostgresNotesFixture { Keep = ["Countrys"] };
        await fixture.InitializeAsync();

        Exception? error = await Record.ExceptionAsync(fixture.ResetDataAsync);

        Assert.Null(error);
    }

    // A fixture's database with a parent and child, a partitioned table, identity, serial and default-drawn ids (one on the
    // partitioned table), kept tables spelled three ways, and migrations histories under EF Core's default name and a
    // custom one.
    private sealed class ResetDatabase : IAsyncDisposable
    {
        private const string Schema = """
            CREATE SCHEMA ref;
            CREATE TABLE "Countries" ("Name" text PRIMARY KEY);
            CREATE TABLE ref."Regions" ("Name" text PRIMARY KEY);
            CREATE TABLE ref."Zones" ("Name" text PRIMARY KEY);
            CREATE TABLE "__EFMigrationsHistory" ("MigrationId" text PRIMARY KEY, "ProductVersion" text NOT NULL);
            CREATE TABLE "MigrationLog" ("MigrationId" text PRIMARY KEY, "ProductVersion" text NOT NULL);
            CREATE TABLE "Customers" ("Id" int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);
            CREATE TABLE "Orders" ("Id" serial PRIMARY KEY, "CustomerId" int NOT NULL REFERENCES "Customers" ("Id"));
            CREATE SEQUENCE "ReadingNumbers" START 50;
            CREATE TABLE "Readings" ("Number" int NOT NULL DEFAULT nextval('"ReadingNumbers"'), "Day" date NOT NULL)
                PARTITION BY RANGE ("Day");
            CREATE TABLE "Readings2026" PARTITION OF "Readings" FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
            CREATE SEQUENCE "InvoiceNumbers" START 100;
            CREATE SEQUENCE "SharedNumbers" START 200;
            CREATE SEQUENCE "HiLoNumbers" START 300;
            ALTER TABLE "Countries" ADD COLUMN "Number" int NOT NULL DEFAULT nextval('"SharedNumbers"');
            CREATE TABLE "Tickets" ("Id" int PRIMARY KEY DEFAULT nextval('"SharedNumbers"'));
            CREATE TABLE "Invoices" ("Id" int PRIMARY KEY DEFAULT nextval('"InvoiceNumbers"'));
            INSERT INTO "Countries" VALUES ('North');
            INSERT INTO ref."Regions" VALUES ('East');
            INSERT INTO ref."Zones" VALUES ('Coast');
            INSERT INTO "__EFMigrationsHistory" VALUES ('20260101000000_Initial', '10.0.0');
            INSERT INTO "MigrationLog" VALUES ('20260101000000_Initial', '10.0.0');
            INSERT INTO "Customers" DEFAULT VALUES;
            INSERT INTO "Orders" ("CustomerId") VALUES (1);
            INSERT INTO "Readings" ("Day") VALUES ('2026-05-01');
            INSERT INTO "Invoices" DEFAULT VALUES;
            INSERT INTO "Tickets" DEFAULT VALUES;
            SELECT nextval('"HiLoNumbers"');
            """;

        private ResetDatabase(PostgresNotesFixture fixture)
        {
            Fixture = fixture;
        }

        public PostgresNotesFixture Fixture { get; }

        public static async Task<ResetDatabase> CreateAsync()
        {
            await PostgresNotesFixture.SkipWithoutServerAsync();
            var fixture = new PostgresNotesFixture { Keep = ["Countries", "ref.Regions", "\"ref\".\"Zones\""] };
            await fixture.InitializeAsync();
            var db = new ResetDatabase(fixture);
            string database = new NpgsqlConnectionStringBuilder(fixture.Postgres.ConnectionString("Notes")).Database!;
            await db.ScalarAsync($"CREATE DATABASE \"{database}\"", "postgres");
            await db.ScalarAsync(Schema);
            return db;
        }

        public Task<object?> ScalarAsync(string sql, string? database = null) => Fixture.ScalarAsync(sql, database);

        public ValueTask DisposeAsync() => Fixture.DisposeAsync();
    }
}
